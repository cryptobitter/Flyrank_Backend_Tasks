"""
Automated PDF Incident Post-Mortem Generator:
Uses ReportLab to compile executive-ready post-mortem PDF documents
with timeline diagrams, root-cause analyses, and mitigation checklists.
"""

import os
from datetime import datetime, timezone
from pathlib import Path
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from config import REPORTS_DIR


def generate_post_mortem_pdf(
    incident_id: str,
    title: str,
    service_name: str,
    severity: str,
    root_cause: str,
    mitigation_steps: str,
    executive_summary: str,
    impact_duration_min: int = 45,
    resolved_at: str = "2026-10-20 20:30 UTC",
) -> str:
    """
    Builds a professional executive incident report PDF.
    Returns the absolute filepath to the generated PDF.
    """
    output_filename = f"postmortem_{incident_id[:8]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
    pdf_path = REPORTS_DIR / output_filename

    doc = SimpleDocTemplate(
        str(pdf_path),
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0f172a"),
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#6366f1"),
    )
    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor("#334155"),
    )

    elements = []

    # 1. Header Banner
    elements.append(Paragraph("SENTINEL AI · INCIDENT MANAGEMENT PLATFORM", subtitle_style))
    elements.append(Spacer(1, 4))
    elements.append(Paragraph(f"Executive Post-Mortem: {title}", title_style))
    elements.append(Spacer(1, 8))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#6366f1"), spaceAfter=15))

    # 2. Metadata Table
    sev_color = colors.HexColor("#dc2626") if "P1" in severity else colors.HexColor("#ea580c")
    meta_data = [
        [
            Paragraph("<b>Incident ID:</b>", body_style),
            Paragraph(incident_id, body_style),
            Paragraph("<b>Severity:</b>", body_style),
            Paragraph(f"<font color='{sev_color.hexval()}'><b>{severity}</b></font>", body_style),
        ],
        [
            Paragraph("<b>Impacted Service:</b>", body_style),
            Paragraph(service_name, body_style),
            Paragraph("<b>Downtime Duration:</b>", body_style),
            Paragraph(f"{impact_duration_min} minutes", body_style),
        ],
        [
            Paragraph("<b>Generated By:</b>", body_style),
            Paragraph("SentinelAI Autonomous SRE", body_style),
            Paragraph("<b>Resolution Timestamp:</b>", body_style),
            Paragraph(resolved_at, body_style),
        ],
    ]
    meta_table = Table(meta_data, colWidths=[1.5 * inch, 2.0 * inch, 1.5 * inch, 2.0 * inch])
    meta_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ])
    )
    elements.append(meta_table)
    elements.append(Spacer(1, 15))

    # 3. Executive Summary
    elements.append(Paragraph("1. Executive Summary", section_heading))
    elements.append(Paragraph(executive_summary, body_style))
    elements.append(Spacer(1, 10))

    # 4. Root Cause Analysis
    elements.append(Paragraph("2. Technical Root-Cause Analysis", section_heading))
    elements.append(Paragraph(root_cause, body_style))
    elements.append(Spacer(1, 10))

    # 5. Immediate Mitigation & Recovery Steps
    elements.append(Paragraph("3. Remediation & Tactical Mitigation", section_heading))
    elements.append(Paragraph(mitigation_steps.replace("\n", "<br/>"), body_style))
    elements.append(Spacer(1, 10))

    # 6. Action Items Checklist
    elements.append(Paragraph("4. Preventative Action Items & SRE Follow-Up", section_heading))
    checklist_data = [
        [Paragraph("<b>Status</b>", body_style), Paragraph("<b>Item</b>", body_style), Paragraph("<b>Owner</b>", body_style)],
        [Paragraph("[ ] DONE", body_style), Paragraph("Deploy container memory limits / pool expansion patch", body_style), Paragraph("DevOps Team", body_style)],
        [Paragraph("[ ] IN PROGRESS", body_style), Paragraph("Add Datadog threshold monitor for connection pool exhaustion", body_style), Paragraph("SRE On-Call", body_style)],
        [Paragraph("[ ] BACKLOG", body_style), Paragraph("Simulate chaos scenario in staging environment", body_style), Paragraph("QA / SecOps", body_style)],
    ]
    check_table = Table(checklist_data, colWidths=[1.2 * inch, 4.3 * inch, 1.5 * inch])
    check_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#94a3b8")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ])
    )
    elements.append(check_table)
    elements.append(Spacer(1, 20))

    # Footer note
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#94a3b8"), spaceAfter=10))
    elements.append(Paragraph("Confidential — Generated by SentinelAI for Internal Engineering & Executive Review.", ParagraphStyle("Foot", parent=styles["Normal"], fontSize=8, textColor=colors.HexColor("#64748b"))))

    doc.build(elements)
    return str(pdf_path)
